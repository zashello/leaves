static void ssd1309WriteCommand(uint8_t cmd)
{
  i2cSoftStart();
  i2cSoftSendByte(g_config.address << 1);
  i2cSoftWaitAck();
  i2cSoftSendByte(0x00);
  i2cSoftWaitAck();
  i2cSoftSendByte(cmd);
  i2cSoftWaitAck();
  i2cSoftStop();
}

static void ssd1309WriteCommand2(uint8_t cmd, uint8_t param)
{
  i2cSoftStart();
  i2cSoftSendByte(g_config.address << 1);
  i2cSoftWaitAck();
  i2cSoftSendByte(0x00);
  i2cSoftWaitAck();
  i2cSoftSendByte(cmd);
  i2cSoftWaitAck();
  i2cSoftSendByte(param);
  i2cSoftWaitAck();
  i2cSoftStop();
}

static void ssd1309WriteData(uint8_t *data, uint16_t len)
{
  if (data == NULL || len == 0) return;

  i2cSoftStart();
  i2cSoftSendByte(g_config.address << 1);
  i2cSoftWaitAck();
  i2cSoftSendByte(0x40);
  i2cSoftWaitAck();

  for (uint16_t i = 0; i < len; i++) {
    i2cSoftSendByte(data[i]);
    i2cSoftWaitAck();
  }

  i2cSoftStop();
}

esp_err_t ssd1309Init(const ssd1309_config_t *config)
{
  if (config == NULL) {
    return ESP_ERR_INVALID_ARG;
  }

  if (g_initialized) {
    ESP_LOGW(TAG, "SSD1309已初始化");
    return ESP_OK;
  }

  memcpy(&g_config, config, sizeof(ssd1309_state_t));

  ESP_LOGI(TAG, "初始化SSD1309: 地址=0x%02X, SCL=GPIO%d, SDA=GPIO%d, RST=GPIO%d",
           g_config.address, g_config.sclPin, g_config.sdaPin, g_config.rstPin);

  // RST硬件复位
  if (g_config.rstPin >= 0) {
    gpio_config_t rstConf = {
      .pin_bit_mask = (1ULL << g_config.rstPin),
      .mode = GPIO_MODE_OUTPUT,
      .pull_up_en = GPIO_PULLUP_ENABLE,
      .pull_down_en = GPIO_PULLDOWN_DISABLE,
      .intr_type = GPIO_INTR_DISABLE
    };
    gpio_config(&rstConf);

    gpio_set_level(g_config.rstPin, 0);
    esp_rom_delay_us(20000);
    gpio_set_level(g_config.rstPin, 1);
    esp_rom_delay_us(20000);
    ESP_LOGI(TAG, "SSD1309 RST复位完成");
  }

  esp_err_t ret = i2cSoftInit(g_config.sclPin, g_config.sdaPin);
  if (ret != ESP_OK) {
    ESP_LOGE(TAG, "软件I2C初始化失败");
    return ret;
  }

  i2cSoftStart();
  i2cSoftSendByte(g_config.address << 1);
  i2cSoftWaitAck();
  i2cSoftStop();

  // SSD1309正确初始化序列
  ssd1309WriteCommand2(0xFD, 0x12);  // 解锁命令锁
  ssd1309WriteCommand(0xAE);         // 显示OFF
  ssd1309WriteCommand2(0xD5, 0xA0);  // 时钟分频
  ssd1309WriteCommand2(0xA8, 0x3F);  // MUX=64 (128x64)
  ssd1309WriteCommand2(0xD3, 0x00);  // 显示偏移
  ssd1309WriteCommand(0x40);         // 起始行=0
  ssd1309WriteCommand2(0x8D, 0x14);  // 电荷泵使能 (部分SSD1309模块需要)
  ssd1309WriteCommand2(0x20, 0x00);  // 水平寻址模式
  ssd1309WriteCommand(0xA1);         // 段重映射 (列127→SEG0)
  ssd1309WriteCommand(0xC8);         // COM扫描方向 (重映射)
  ssd1309WriteCommand2(0xDA, 0x12);  // COM引脚配置 (128x64)
  ssd1309WriteCommand2(0x81, 0xCF);  // 对比度
  ssd1309WriteCommand2(0xD9, 0x22);  // 预充电 (SSD1309)
  ssd1309WriteCommand2(0xDB, 0x40);  // VCOMH (SSD1309)
  ssd1309WriteCommand(0xA4);         // 恢复正常 (跟随RAM)
  ssd1309WriteCommand(0xA6);         // 非反相显示
  ssd1309WriteCommand(0x2E);         // 停止滚动
  ssd1309WriteCommand(0xAF);         // 显示ON

  memset(g_buffer, 0, SSD1309_BUFFER_SIZE);
  g_cursorX = 0;
  g_cursorY = 0;

  g_initialized = true;
  ESP_LOGI(TAG, "SSD1309初始化成功");
  return ESP_OK;
}

void ssd1309Deinit(void)
{
  if (!g_initialized) return;

  i2cSoftDeinit();
  g_initialized = false;
  ESP_LOGI(TAG, "SSD1309已释放");
}

void ssd1309Clear(void)
{
  if (!g_initialized) return;

  memset(g_buffer, 0, SSD1309_BUFFER_SIZE);
  g_cursorX = 0;
  g_cursorY = 0;
}

void ssd1309Display(void)
{
  if (!g_initialized) return;

  ssd1309WriteCommand(0x21);
  ssd1309WriteCommand(g_config.columnOffset);
  ssd1309WriteCommand(127);
  ssd1309WriteCommand(0x22);
  ssd1309WriteCommand(g_config.pageOffset);
  ssd1309WriteCommand(7);

  uint8_t displayData[128 * 8];
  memset(displayData, 0, sizeof(displayData));

  for (int page = 0; page < 8; page++) {
    int bufferStartOffset = (page - g_config.pageOffset) * 128;
    if (bufferStartOffset >= 0 && bufferStartOffset < SSD1309_BUFFER_SIZE) {
      int copyLen = 127 - g_config.columnOffset + 1;
      if (copyLen > 128) copyLen = 128;
      if (bufferStartOffset + copyLen <= SSD1309_BUFFER_SIZE) {
        memcpy(displayData + page * 128, g_buffer + bufferStartOffset + g_config.columnOffset, copyLen);
      }
    }
  }

  ssd1309WriteData(displayData, 128 * (8 - g_config.pageOffset));
}

void ssd1309DrawPixel(int16_t x, int16_t y, uint8_t color)
{
  if (!g_initialized) return;

  if (x < g_config.columnOffset || y < g_config.pageOffset * 8 ||
    x >= g_config.width || y >= g_config.height) {
    return;
  }

  int16_t bufX = x - g_config.columnOffset;
  int16_t bufY = (y / 8) - g_config.pageOffset;
  uint16_t index = bufY * 128 + bufX;

  if (index >= SSD1309_BUFFER_SIZE) return;

  uint8_t bitMask = 1 << (y & 7);

  if (color == SSD1309_WHITE) {
    g_buffer[index] |= bitMask;
  } else {
    g_buffer[index] &= ~bitMask;
  }
}

void ssd1309SetCursor(int16_t x, int16_t y)
{
  if (x < 0) x = 0;
  if (y < 0) y = 0;
  g_cursorX = x;
  g_cursorY = y;
}

void ssd1309Write(char c)
{
  if (!g_initialized) return;

  if (c < 32 || c > 126) {
    c = ' ';
  }

  const uint8_t *charData = font5x7[c - 32];

  for (int col = 0; col < FONT_W; col++) {
    uint8_t colData = charData[col];
    for (int row = 0; row < FONT_H; row++) {
      if (colData & (1 << row)) {
        ssd1309DrawPixel(g_cursorX + col, g_cursorY + row, SSD1309_WHITE);
      }
    }
  }

  g_cursorX += FONT_STEP;
}

void ssd1309Print(const char *text)
{
  if (text == NULL) return;

  while (*text) {
    ssd1309Write(*text);
    text++;
  }
}

void ssd1309PrintFloat(float value, uint8_t decimals)
{
  if (!g_initialized) return;

  char str[20];
  snprintf(str, sizeof(str), "%.*f", decimals, value);
  ssd1309Print(str);
}
